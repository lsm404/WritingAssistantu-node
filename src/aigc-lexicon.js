function pickFrom(arr, rng) {
  return arr[Math.floor(rng() * arr.length)];
}

function normalizePunctuation(text) {
  return text
    .replace(/，{2,}/g, "，")
    .replace(/,{2,}/g, "，")
    .replace(/，。/g, "。")
    .replace(/,\s*。/g, "。")
    .replace(/[ \t]+([，。！？；：])/g, "$1");
}

export function applyAigcLexiconReplacements(value, options = {}) {
  if (!value || typeof value !== "string") return value;

  const rng = typeof options.rng === "function" ? options.rng : Math.random;
  const probability = Number.isFinite(options.probability) ? options.probability : 0.86;
  const pickUnique = typeof options.pickUnique === "function" ? options.pickUnique : (arr) => pickFrom(arr, rng);
  const pick = (arr) => pickFrom(arr, rng);

  let text = value;

  for (const phrase of AIGC_NUKE_PHRASES) {
    if (text.includes(phrase)) {
      text = text.split(phrase).join("");
    }
  }

  for (const rule of AIGC_PATTERN_REPLACEMENTS) {
    text = text.replace(rule.pattern, (...args) => {
      const match = args[0];
      if (rng() > probability) return match;
      return rule.replace({ args, match, pick, pickUnique, rng });
    });
  }

  const sortedRules = [...AIGC_WORD_REPLACEMENTS].sort((a, b) => b.source.length - a.source.length);
  for (const rule of sortedRules) {
    if (!text.includes(rule.source)) continue;
    text = text
      .split(rule.source)
      .map((part, index, parts) => {
        if (index === parts.length - 1) return part;
        return part + (rng() < probability ? pickUnique(rule.alternatives) : rule.source);
      })
      .join("");
  }

  return normalizePunctuation(text);
}

export function buildAigcReplacementInstruction(maxItems = 320) {
  const lines = [];
  let count = 0;

  for (const group of AIGC_REPLACEMENT_GROUPS) {
    if (count >= maxItems) break;
    lines.push(`### ${group.name}`);
    for (const [source, alternatives] of group.items) {
      if (count >= maxItems) break;
      lines.push(`- ${source} -> ${alternatives.join(" / ")}`);
      count += 1;
    }
    lines.push("");
  }

  return [
    "## 词汇替换强化表",
    "",
    "优先把下列 AI 常见词、连接词、抽象词和套话换成更具体、更口语、更贴近公众号人工改写的表达。不要机械全量替换，要看上下文保留少量自然重复。",
    "",
    ...lines,
  ]
    .join("\n")
    .trim();
}


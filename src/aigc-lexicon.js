/**
 * 应用句式替换规则组（负责 A~U 所有句式改写）
 * @param {string} text
 * @param {{ rng: Function, makeScopedPickU: Function, sentinel: string }} ctx
 * @returns {string}
 */
export function applyAigcSentencePatterns(text, ctx) {
  const { rng, makeScopedPickU, sentinel } = ctx;

  for (const rule of AIGC_SENTENCE_PATTERN_GROUPS) {
    const pickU = makeScopedPickU();
    const pick = (arr) => arr[Math.floor(rng() * arr.length)];

    text = text.replace(rule.pattern, (...args) => {
      const match = args[0];
      const groups = args.slice(1, -2); // 去掉 offset 和 string
      if (rule.build) {
        // build 的最后一个参数约定为 pickU
        const result = rule.build(match, ...groups, pickU);
        return result !== undefined ? sentinel + result : match;
      }
      if (rule.alts) {
        return sentinel + pickU(rule.alts);
      }
      return match;
    });
  }

  return text;
}

/**
 * 应用口语词汇替换表（负责单词级别改写）
 * @param {string} text
 * @param {{ rng: Function, makeScopedPickU: Function, sentinel: string, probability?: number }} ctx
 * @returns {string}
 */
export function applyAigcInlineWordReplacements(text, ctx) {
  const { rng, makeScopedPickU, sentinel } = ctx;
  const probability = ctx.probability ?? 0.85;

  for (const [word, alts, regex] of AIGC_INLINE_WORD_REPLACEMENTS) {
    const wordPickU = makeScopedPickU();
    if (regex) {
      text = text.replace(regex, (match) =>
        rng() < probability ? sentinel + wordPickU(alts) : match,
      );
    } else {
      if (!text.includes(word)) continue;
      text = text
        .split(word)
        .map((p, i, a) =>
          i === a.length - 1 ? p : p + (rng() < probability ? sentinel + wordPickU(alts) : word),
        )
        .join("");
    }
  }

  return text;
}
